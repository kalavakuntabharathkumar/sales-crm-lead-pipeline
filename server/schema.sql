CREATE TABLE IF NOT EXISTS leads (
  id SERIAL PRIMARY KEY, name TEXT NOT NULL, owner TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT now()
);
CREATE TABLE IF NOT EXISTS companies (
  id SERIAL PRIMARY KEY, name TEXT NOT NULL, owner TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT now()
);
CREATE TABLE IF NOT EXISTS contacts (
  id SERIAL PRIMARY KEY, name TEXT NOT NULL, owner TEXT NOT NULL,
  created_at TIMESTAMPTZ DEFAULT now()
);
CREATE TABLE IF NOT EXISTS opportunities (
  id SERIAL PRIMARY KEY, title TEXT NOT NULL, value NUMERIC(12,2) NOT NULL,
  stage TEXT NOT NULL, created_at TIMESTAMPTZ DEFAULT now()
);
CREATE TABLE IF NOT EXISTS workflows (
  id SERIAL PRIMARY KEY, name TEXT NOT NULL, event TEXT NOT NULL,
  condition TEXT NOT NULL, action TEXT NOT NULL, created_at TIMESTAMPTZ DEFAULT now()
);
